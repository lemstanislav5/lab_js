<?php
    $cardNum = 11; // Пример номера карты от пользователя

    // Справочник текстовых названий для карт старше десятки
    $cardsLookup = [
        11 => "валет",
        12 => "дама",
        13 => "король",
        14 => "туз"
    ];

    if ($cardNum >= 6 && $cardNum <= 10) {
        // Для карт от 6 до 10 достоинство совпадает с числом
        echo "Достоинство карты: $cardNum";
    } elseif (isset($cardsLookup[$cardNum])) {
        // Для картинок выводим имя из справочника
        echo "Достоинство карты: " . $cardsLookup[$cardNum];
    } else {
        echo "Ошибка: некорректный порядковый номер карты (введите от 6 до 14).";
    }
?>
