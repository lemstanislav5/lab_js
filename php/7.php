    // Пример введенных градусов (от 0 до 360)
    $degrees = 95; 

    if ($degrees < 0 || $degrees > 360) {
        echo "Ошибка: введите число от 0 до 360.";
    } else {
        // 360 градусов / 12 часов = 30 градусов на 1 час
        $hours = floor($degrees / 30);
        
        echo "По введенным градусам ($degrees°) прошло полных часов: $hours";
    }
?>
