<?php
    $sum = 0;
    echo "Числа, которые делятся на 5: ";

    for ($i = 20; $i <= 45; $i++) {
        // fmod возвращает остаток от деления. Если он равен 0, число делится нацело
        if (fmod($i, 5) == 0) {
            echo $i . " ";
            $sum += $i;
        }
    }

    echo "<br>Сумма этих чисел: " . $sum; 
?>
