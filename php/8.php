<?php
    // Пример: текущая минута внутри часа (от 0 до 59)
    $minute = 14; 

    if ($minute < 0 || $minute >= 60) {
        echo "Ошибка: введите минуту от 0 до 59.";
    } else {
        // Находим минуту внутри 5-минутного цикла светофора
        $cycleMinute = $minute % 5;

        // С 0-й по 3-ю минуту (не включая 3-ю) — зеленый. То есть: 0, 1, 2.
        if ($cycleMinute < 3) {
            $signal = "ЗЕЛЕНЫЙ";
        } else {
            // Минуты 3 и 4 — красный.
            $signal = "КРАСНЫЙ";
        }

        echo "На $minute-й минуте часа горит $signal сигнал.";
    }
?>
