    $year = 2024; 

    if ($year < 1 || $year > 9999) {
        echo "Ошибка: введите год в диапазоне от 1 до 9999.";
    } else {
        // Проверка на высокосный год
        if (($year % 4 == 0 && $year % 100 != 0) || ($year % 400 == 0)) {
            echo "Год $year — высокосный.";
        } else {
            echo "Год $year — обычный (невысокосный).";
        }
    }
?>
