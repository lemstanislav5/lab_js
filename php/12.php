<?php
    $n = 15; // Дано натуральное число n
    $sum = 0;

    echo "Квадраты чисел от 1 до $n:<br>";

    for ($i = 1; $i <= $n; $i++) {
        $square = $i ** 2; // Возведение в квадрат ($i * $i)
        echo "$i² = $square<br>";
        $sum += $square; // Прибавляем к общей сумме
    }

    echo "<br>Сумма квадратов этих чисел равна: $sum";
?>
